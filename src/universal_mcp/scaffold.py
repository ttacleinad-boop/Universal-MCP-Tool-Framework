from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

PROJECT_TYPES = {"python-library", "mcp-tool"}
REQUIRED_DIRECTORIES = ("src", "tests", "config", "scripts", "docs")
REQUIRED_FILES = (
    "README.md",
    ".gitignore",
    ".project-state.json",
    "pyproject.toml",
    "config/development.json",
    "config/production.json",
    "scripts/setup.sh",
    "scripts/setup.ps1",
)


class ScaffoldError(ValueError):
    """Raised when a project cannot be safely scaffolded."""


@dataclass(frozen=True)
class ScaffoldResult:
    project_root: str
    project_type: str
    package_name: str
    git_initialized: bool
    dependencies_installed: bool
    validation: dict[str, Any]

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


def _package_name(project_name: str) -> str:
    normalized = re.sub(r"[^a-z0-9]+", "_", project_name.lower()).strip("_")
    if not normalized or normalized[0].isdigit():
        raise ScaffoldError("project name must produce a valid Python package name")
    return normalized


def _write(root: Path, relative_path: str, content: str, *, executable: bool = False) -> None:
    destination = root / relative_path
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(content, encoding="utf-8")
    if executable:
        destination.chmod(destination.stat().st_mode | 0o111)


def _pyproject(project_name: str, package_name: str, project_type: str) -> str:
    distribution_name = package_name.replace("_", "-")
    dependencies = ['  "mcp==2.0.0"'] if project_type == "mcp-tool" else []
    dependencies_block = "\n".join(dependencies)
    if dependencies_block:
        dependencies_block = f"\ndependencies = [\n{dependencies_block}\n]\n"
    return f'''[build-system]
requires = ["setuptools>=68"]
build-backend = "setuptools.build_meta"

[project]
name = "{distribution_name}"
version = "0.1.0"
description = "{project_name}"
readme = "README.md"
requires-python = ">=3.10"{dependencies_block}
[project.optional-dependencies]
dev = []

[tool.setuptools]
package-dir = {{"" = "src"}}

[tool.setuptools.packages.find]
where = ["src"]
'''


def _readme(project_name: str, project_type: str) -> str:
    return f'''# {project_name}

Generated by the Universal Project Scaffolding Toolkit.

## Project State

Project type: `{project_type}`. The canonical project state is stored in `.project-state.json`.

## Development

```bash
./scripts/setup.sh
python -m unittest discover -s tests -p "test_*.py"
```

On Windows PowerShell:

```powershell
./scripts/setup.ps1
python -m unittest discover -s tests -p "test_*.py"
```

## Validation

```bash
umcp-scaffold validate .
```
'''


def _source_template(package_name: str, project_type: str) -> dict[str, str]:
    files = {
        f"src/{package_name}/__init__.py": '__version__ = "0.1.0"\n',
        f"tests/test_{package_name}.py": f'''import unittest

from {package_name} import __version__


class PackageTests(unittest.TestCase):
    def test_version_exists(self) -> None:
        self.assertEqual(__version__, "0.1.0")


if __name__ == "__main__":
    unittest.main()
''',
    }
    if project_type == "mcp-tool":
        files[f"src/{package_name}/server.py"] = f'''from mcp.server import MCPServer

mcp = MCPServer("{package_name}")


@mcp.tool()
def health() -> dict[str, str]:
    """Return basic MCP tool health."""
    return {{"status": "ok"}}
'''
        files["server.py"] = f"from {package_name}.server import mcp\n"
    return files


def _setup_sh() -> str:
    return """#!/usr/bin/env sh
set -eu
python3 -m venv .venv
. .venv/bin/activate
python -m pip install --upgrade pip
python -m pip install -e \".[dev]\"
"""


def _setup_ps1() -> str:
    return """$ErrorActionPreference = \"Stop\"
python -m venv .venv
& .\\.venv\\Scripts\\python.exe -m pip install --upgrade pip
& .\\.venv\\Scripts\\python.exe -m pip install -e \".[dev]\"
"""


def _run(command: list[str], *, cwd: Path, env: dict[str, str] | None = None) -> dict[str, Any]:
    completed = subprocess.run(
        command,
        cwd=cwd,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    return {
        "command": command,
        "passed": completed.returncode == 0,
        "returncode": completed.returncode,
        "output": (completed.stdout + completed.stderr).strip(),
    }


def validate_project(project_root: str | Path) -> dict[str, Any]:
    root = Path(project_root).resolve()
    checks: list[dict[str, Any]] = []
    checks.append({"check": "project_root", "passed": root.is_dir()})

    for relative in REQUIRED_DIRECTORIES:
        checks.append({"check": f"directory:{relative}", "passed": (root / relative).is_dir()})
    for relative in REQUIRED_FILES:
        checks.append({"check": f"file:{relative}", "passed": (root / relative).is_file()})

    state_path = root / ".project-state.json"
    package_name = None
    if state_path.is_file():
        try:
            state = json.loads(state_path.read_text(encoding="utf-8"))
            package_name = state["package_name"]
            checks.append({"check": "state_file", "passed": isinstance(package_name, str)})
        except (json.JSONDecodeError, KeyError, TypeError):
            checks.append({"check": "state_file", "passed": False})

    if package_name:
        source_root = root / "src"
        env = {**os.environ, "PYTHONPATH": str(source_root)}
        checks.append({
            "check": "source_compiles",
            **_run([sys.executable, "-m", "compileall", "-q", "src"], cwd=root, env=env),
        })
        checks.append({
            "check": "tests_pass", 
            **_run(
                [sys.executable, "-m", "unittest", "discover", "-s", "tests", "-p", "test_*.py"],
                cwd=root,
                env=env,
            ),
        })

    return {
        "project_root": str(root),
        "runnable": all(check["passed"] for check in checks),
        "checks": checks,
    }


def scaffold_project(
    project_name: str,
    project_root: str | Path,
    *,
    project_type: str = "python-library",
    initialize_git: bool = True,
    install_dependencies: bool = True,
) -> ScaffoldResult:
    if project_type not in PROJECT_TYPES:
        options = ", ".join(sorted(PROJECT_TYPES))
        raise ScaffoldError(f"unsupported project type '{project_type}'; choose: {options}")

    root = Path(project_root).resolve()
    if root.exists() and any(root.iterdir()):
        raise ScaffoldError(f"target directory is not empty: {root}")
    root.mkdir(parents=True, exist_ok=True)
    package_name = _package_name(project_name)

    for directory in REQUIRED_DIRECTORIES:
        (root / directory).mkdir(parents=True, exist_ok=True)

    state = {
        "schema_version": 1,
        "name": project_name,
        "package_name": package_name,
        "project_type": project_type,
        "lifecycle_state": "initialized",
        "created_utc": datetime.now(timezone.utc).isoformat(),
    }
    files = {
        "README.md": _readme(project_name, project_type),
        ".gitignore": "__pycache__/\n*.py[cod]\n*.egg-info/\n.venv/\n.pytest_cache/\n.coverage\n",
        ".project-state.json": json.dumps(state, indent=2) + "\n",
        "pyproject.toml": _pyproject(project_name, package_name, project_type),
        "config/development.json": json.dumps({"environment": "development", "debug": True}, indent=2) + "\n",
        "config/production.json": json.dumps({"environment": "production", "debug": False}, indent=2) + "\n",
        "scripts/setup.sh": _setup_sh(),
        "scripts/setup.ps1": _setup_ps1(),
        "docs/PROJECT_CONVENTIONS.md": "# Project Conventions\n\nKeep project state current in `.project-state.json`. Add tests with every change.\n",
    }
    files.update(_source_template(package_name, project_type))
    for relative, content in files.items():
        _write(root, relative, content, executable=relative == "scripts/setup.sh")

    git_initialized = False
    if initialize_git:
        result = _run(["git", "init"], cwd=root)
        if not result["passed"]:
            raise ScaffoldError(f"git initialization failed: {result['output']}")
        git_initialized = True

    dependencies_installed = False
    if install_dependencies:
        venv = _run([sys.executable, "-m", "venv", ".venv"], cwd=root)
        if not venv["passed"]:
            raise ScaffoldError(f"virtual-environment setup failed: {venv['output']}")
        venv_python = root / ".venv" / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
        install = _run([str(venv_python), "-m", "pip", "install", "-e", ".[dev]"], cwd=root)
        if not install["passed"]:
            raise ScaffoldError(f"dependency installation failed: {install['output']}")
        dependencies_installed = True

    validation = validate_project(root)
    state.update(
        {
            "git_initialized": git_initialized,
            "dependencies_installed": dependencies_installed,
            "validation_state": "pass" if validation["runnable"] else "fail",
        }
    )
    _write(root, ".project-state.json", json.dumps(state, indent=2) + "\n")
    return ScaffoldResult(
        project_root=str(root),
        project_type=project_type,
        package_name=package_name,
        git_initialized=git_initialized,
        dependencies_installed=dependencies_installed,
        validation=validation,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Universal Project Scaffolding Toolkit")
    subparsers = parser.add_subparsers(dest="command", required=True)

    create = subparsers.add_parser("create", help="Create and validate a new project")
    create.add_argument("name")
    create.add_argument("path")
    create.add_argument("--type", choices=sorted(PROJECT_TYPES), default="python-library")
    create.add_argument("--no-git", action="store_true", help="Do not initialize a Git repository")
    create.add_argument("--no-install", action="store_true", help="Do not install local project dependencies")

    validate = subparsers.add_parser("validate", help="Validate a scaffolded project")
    validate.add_argument("path")

    args = parser.parse_args()
    if args.command == "create":
        result = scaffold_project(
            args.name,
            args.path,
            project_type=args.type,
            initialize_git=not args.no_git,
            install_dependencies=not args.no_install,
        ).as_dict()
    else:
        result = validate_project(args.path)
    print(json.dumps(result, indent=2))
    if not result["validation"]["runnable"] if args.command == "create" else not result["runnable"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
